DO $$ BEGIN
  IF current_schema() NOT IN ('public','crm_staging') THEN RAISE EXCEPTION 'Explicit public/crm_staging search_path required'; END IF;
END $$;
CREATE TABLE IF NOT EXISTS revisit_email_templates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 80),
  subject text NOT NULL CHECK (length(subject) BETWEEN 1 AND 200),
  preheader text NOT NULL DEFAULT '' CHECK (length(preheader)<=300),
  body_text text NOT NULL CHECK (length(body_text) BETWEEN 1 AND 4000),
  created_by text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE revisit_email_templates ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON revisit_email_templates FROM PUBLIC;
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
    REVOKE ALL ON revisit_email_templates FROM anon, authenticated;
  END IF;
  IF current_schema()='crm_staging' AND EXISTS (SELECT 1 FROM pg_roles WHERE rolname='crm_staging_app') THEN
    GRANT SELECT,INSERT ON revisit_email_templates TO crm_staging_app;
    GRANT USAGE,SELECT ON SEQUENCE revisit_email_templates_id_seq TO crm_staging_app;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname=current_schema() AND tablename='revisit_email_templates' AND policyname='revisit_templates_staging_app') THEN
      CREATE POLICY revisit_templates_staging_app ON revisit_email_templates FOR ALL TO crm_staging_app USING (true) WITH CHECK (true);
    END IF;
  END IF;
END $$;
